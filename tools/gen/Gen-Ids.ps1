<#
 Generates the Rust constants of the crate ei-data from the C# ID files (phase 4.1):
   SkillIDs.cs     -> generated/skill_ids.rs    (const long)
   SpeciesIDs.cs   -> generated/species_ids.rs  (enums TargetID, MinionID, ChestID and the const int of SpeciesIDs)
   EffectGUIDs.cs  -> generated/effect_guids.rs (Guid)
   MarkerGUIDs.cs  -> generated/marker_guids.rs (Guid)
 Every declaration that cannot be parsed or whose Rust name collides makes the script fail, so the
 result is complete or there is none. A summary of the counts is printed (and checked by a Rust test).
 Usage: Gen-Ids.ps1 [-Root <repo root>]
#>
param([string]$Root = '')
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)) }
$helpers = Join-Path $Root 'GW2EI.Library\GW2EI.Services\GW2EIEvtcParser\ParserHelpers'
$outDir = Join-Path $Root 'rust\ei-data\src\generated'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

function ToScreaming([string]$n) {
    $lead = if ($n.StartsWith('_')) { 'X' } else { '' }
    $n = $n.TrimStart('_')
    $s = ($n -creplace '([a-z0-9])([A-Z])', '$1_$2' -creplace '([A-Z]+)([A-Z][a-z])', '$1_$2').ToUpperInvariant()
    $s = $s -replace '[^A-Z0-9_]', '_'
    if ($lead) { $s = "${lead}_$s" }
    if ($s -match '^[0-9]') { $s = "N_$s" }
    $s
}
function Rust-Int([int]$v) { if ($v -eq [int]::MaxValue) { 'i32::MAX' } elseif ($v -eq [int]::MinValue) { 'i32::MIN' } else { "$v" } }
function Strip([string]$line) { ($line -replace '//.*$', '').Trim() }
function Read-Lines([string]$path) { (Get-Content -Raw -LiteralPath $path) -replace "^﻿", '' -split "`r?`n" }
function Write-Rust([string]$file, [string]$header, [System.Collections.Generic.List[string]]$lines) {
    $text = "// @generated by tools/gen/Gen-Ids.ps1. Do not edit.`n$header`n`n" + ($lines -join "`n") + "`n"
    [IO.File]::WriteAllText((Join-Path $outDir $file), $text, (New-Object Text.UTF8Encoding $false))
}
function Check-Unique($names, [string]$what) {
    $dup = $names | Group-Object | Where-Object Count -gt 1
    if ($dup) { throw "$what : Rust name collision: $(($dup | ForEach-Object Name) -join ', ')" }
}

# ---- SkillIDs ----
$rows = New-Object System.Collections.Generic.List[object]
$expected = 0
foreach ($line in (Read-Lines (Join-Path $helpers 'IDs\SkillIDs.cs'))) {
    $l = Strip $line
    if ($l -notmatch '\bconst long\b') { continue }
    $expected++
    if ($l -match '^(public|internal) const long (?<n>\w+) = (?<v>-?\d+);$') {
        $rows.Add([pscustomobject]@{ Cs = $Matches['n']; Value = $Matches['v']; Vis = $Matches['1'] })
    } elseif ($l -match '^(public|internal) const long (?<n>\w+) = long\.MinValue;$') {
        $rows.Add([pscustomobject]@{ Cs = $Matches['n']; Value = 'i64::MIN'; Vis = 'public' })
    } else { throw "SkillIDs: cannot parse: $l" }
}
if ($rows.Count -ne $expected) { throw 'SkillIDs: count mismatch' }
Check-Unique ($rows | ForEach-Object { ToScreaming $_.Cs }) 'SkillIDs'
$out = New-Object System.Collections.Generic.List[string]
foreach ($r in $rows) { $out.Add("pub const $(ToScreaming $r.Cs): i64 = $($r.Value);") }
Write-Rust 'skill_ids.rs' "//! Skill ids of the C# class ``SkillIDs`` (custom and official, public and internal), same values." $out
$skillCount = $rows.Count

# ---- SpeciesIDs ----
$lines = Read-Lines (Join-Path $helpers 'IDs\SpeciesIDs.cs')
$consts = @{}      # name -> int value (private const int)
$constCount = 0
foreach ($line in $lines) {
    $l = Strip $line
    if ($l -match '\bconst int\b') {
        if ($l -match '^(public|internal|private) const int (?<n>\w+) = (?<v>-?\d+);$') { $consts[$Matches['n']] = [int]$Matches['v']; $constCount++ }
        elseif ($l -match '^(public|internal|private) const int (?<n>\w+) = int\.MinValue;$') { $consts[$Matches['n']] = [int]::MinValue; $constCount++ }
        elseif ($l -match '^(public|internal|private) const int (?<n>\w+) = int\.MaxValue;$') { $consts[$Matches['n']] = [int]::MaxValue; $constCount++ }
        else { throw "SpeciesIDs: cannot parse: $l" }
    }
}
$enums = [ordered]@{}
$current = $null
$pending = @{}
foreach ($line in $lines) {
    $l = Strip $line
    if ($l -match '^public enum (?<n>\w+) : int$') { $current = $Matches['n']; $enums[$current] = New-Object System.Collections.Generic.List[object]; continue }
    if ($null -eq $current) { continue }
    if ($l -eq '{' -or $l -eq '' -or $l.StartsWith('#')) { continue }
    if ($l -eq '}' -or $l -eq '};') { $current = $null; continue }
    if ($l -match '^(?<n>\w+) = (?<v>.+?),?$') { $enums[$current].Add([pscustomobject]@{ Cs = $Matches['n']; Expr = $Matches['v'].Trim() }); continue }
    if ($l -match '^(?<n>\w+),?$') { $enums[$current].Add([pscustomobject]@{ Cs = $Matches['n']; Expr = $null }); continue }
    throw "SpeciesIDs: cannot parse enum line in ${current}: $l"
}
# resolve: literal, int.MaxValue, other member (any enum or const), SpeciesIDs.X
$values = @{}
foreach ($k in $consts.Keys) { $values[$k] = $consts[$k] }
$todo = New-Object System.Collections.Generic.List[object]
foreach ($e in $enums.Keys) {
    $next = 0
    foreach ($m in $enums[$e]) {
        if ($null -eq $m.Expr) { $m | Add-Member -NotePropertyName Resolved -NotePropertyValue $next -Force; $values["$e.$($m.Cs)"] = $next; $next++; continue }
        $expr = $m.Expr -replace '^SpeciesIDs\.', ''
        if ($expr -match '^-?\d+$') { $v = [int]$expr; $m | Add-Member -NotePropertyName Resolved -NotePropertyValue $v -Force; $values["$e.$($m.Cs)"] = $v; $next = $v + 1 }
        elseif ($expr -eq 'int.MaxValue') { $m | Add-Member -NotePropertyName Resolved -NotePropertyValue 2147483647 -Force; $values["$e.$($m.Cs)"] = 2147483647; $next = 0 }
        else { $m | Add-Member -NotePropertyName Ref -NotePropertyValue $expr -Force; $m | Add-Member -NotePropertyName Enum -NotePropertyValue $e -Force; $todo.Add($m) }
    }
}
$progress = $true
while ($todo.Count -gt 0 -and $progress) {
    $progress = $false
    foreach ($m in $todo.ToArray()) {
        $v = $null
        if ($values.ContainsKey($m.Ref)) { $v = $values[$m.Ref] }
        else {
            # a bare name refers to a member of the same enum, a const, or a member of an earlier enum
            $hit = @($values.Keys | Where-Object { $_ -like "*.$($m.Ref)" })
            if ($hit.Count -ge 1) { $v = $values[$hit[0]] }
        }
        if ($null -ne $v) { $m | Add-Member -NotePropertyName Resolved -NotePropertyValue $v -Force; $values["$($m.Enum).$($m.Cs)"] = $v; [void]$todo.Remove($m); $progress = $true }
    }
}
if ($todo.Count -gt 0) { throw "SpeciesIDs: unresolved: $(($todo | ForEach-Object { "$($_.Enum).$($_.Cs) = $($_.Ref)" }) -join '; ')" }
$out = New-Object System.Collections.Generic.List[string]
$out.Add('/// Constants of `SpeciesIDs` itself (placeholder and hand-made ids).')
$out.Add('pub mod species {')
Check-Unique ($consts.Keys | ForEach-Object { ToScreaming $_ }) 'SpeciesIDs consts'
foreach ($k in ($consts.Keys | Sort-Object)) { $out.Add("    pub const $(ToScreaming $k): i32 = $(Rust-Int $consts[$k]);") }
$out.Add('}')
$enumCounts = [ordered]@{}
foreach ($e in $enums.Keys) {
    Check-Unique ($enums[$e] | ForEach-Object { ToScreaming $_.Cs }) "SpeciesIDs.$e"
    $mod = (ToScreaming $e).ToLowerInvariant()
    $out.Add("/// Members of the C# enum ``$e``.")
    $out.Add("pub mod $mod {")
    foreach ($m in $enums[$e]) { $out.Add("    pub const $(ToScreaming $m.Cs): i32 = $(Rust-Int $m.Resolved);") }
    $out.Add('}')
    $enumCounts[$e] = $enums[$e].Count
}
# Vector3 positions of the class (chest gadgets): x, y, z in game units
$out.Add('/// `Vector3` constants of `SpeciesIDs` (positions of chest gadgets), as `[x, y, z]`.')
$out.Add('pub mod positions {')
$positionCount = 0
$positionNames = @()
foreach ($line in $lines) {
    $l = Strip $line
    if ($l -match '\bVector3\b') {
        if ($l -match '^(public|internal|private) static readonly Vector3 (?<n>\w+) = new\((?<x>-?[\d.]+)f, (?<y>-?[\d.]+)f, (?<z>-?[\d.]+)f\);$') {
            $positionNames += (ToScreaming $Matches['n'])
            $out.Add("    pub const $(ToScreaming $Matches['n']): [f32; 3] = [$($Matches['x'])f32, $($Matches['y'])f32, $($Matches['z'])f32];")
            $positionCount++
        } else { throw "SpeciesIDs: cannot parse Vector3: $l" }
    }
}
$out.Add('}')
Check-Unique $positionNames 'SpeciesIDs positions'
Write-Rust 'species_ids.rs' '//! NPC and gadget ids of the C# class ``SpeciesIDs``: its enums and its constants, same values.' $out

# ---- GUIDs ----
function Convert-Guids([string]$srcFile, [string]$dstFile, [string]$header) {
    $rows = New-Object System.Collections.Generic.List[object]
    $expected = 0
    foreach ($line in (Read-Lines $srcFile)) {
        $l = Strip $line
        # sets of GUIDs (IReadOnlyCollection<Guid>) are groupings built from the single GUIDs: not extracted
        if ($l -notmatch '\bGuid \w+ =') { continue }
        $expected++
        if ($l -match '^(public|internal) static readonly Guid (?<n>\w+) = new\("(?<g>[0-9A-Fa-f]{32})"\);$') { $rows.Add([pscustomobject]@{ Cs = $Matches['n']; Hex = $Matches['g'].ToUpperInvariant() }) }
        else { throw "$srcFile : cannot parse: $l" }
    }
    if ($rows.Count -ne $expected) { throw 'GUID count mismatch' }
    Check-Unique ($rows | ForEach-Object { ToScreaming $_.Cs }) $dstFile
    $out = New-Object System.Collections.Generic.List[string]
    foreach ($r in $rows) {
        $bytes = (0..15 | ForEach-Object { '0x' + $r.Hex.Substring($_ * 2, 2) }) -join ', '
        $out.Add("pub const $(ToScreaming $r.Cs): [u8; 16] = [$bytes];")
    }
    Write-Rust $dstFile $header $out
    $rows.Count
}
$guidHeader = '//! GUIDs as the 16 bytes of the 32 hex digits of the C# source, in reading order (not the .NET `Guid` memory layout).'
$effects = Convert-Guids (Join-Path $helpers 'GUIDs\EffectGUIDs.cs') 'effect_guids.rs' $guidHeader
$markers = Convert-Guids (Join-Path $helpers 'GUIDs\MarkerGUIDs.cs') 'marker_guids.rs' $guidHeader

$mods = New-Object System.Collections.Generic.List[string]
foreach ($m in 'buffs', 'effect_guids', 'marker_guids', 'mechanics', 'skill_ids', 'species_ids', 'targets') { $mods.Add("pub mod $m;") }
Write-Rust 'mod.rs' '//! Constants generated from the C# ID files.' $mods
$summary = "skill_ids=$skillCount species_consts=$constCount " + (($enumCounts.Keys | ForEach-Object { "$_=$($enumCounts[$_])" }) -join ' ') + " effect_guids=$effects marker_guids=$markers"
Write-Output $summary
