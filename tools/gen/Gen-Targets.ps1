<#
 Generates rust/ei-data/src/generated/targets.rs from docs/phase7/targets.tsv (written by
 `GW2EIParserReference --dump-targets`): per trigger id the target, trash and friendly NPC species
 of the encounter logic and the sort keys of the targets.
 Usage: Gen-Targets.ps1 [-Tsv <targets.tsv>] [-Out <targets.rs>]
#>
param([string]$Tsv = '', [string]$Out = '')
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path))
if (-not $Tsv) { $Tsv = Join-Path $root 'docs\phase7\targets.tsv' }
if (-not $Out) { $Out = Join-Path $root 'rust\ei-data\src\generated\targets.rs' }
$rows = Import-Csv -Delimiter "`t" -LiteralPath $Tsv -Encoding UTF8
$sb = New-Object System.Text.StringBuilder
function L([string]$s) { [void]$sb.Append($s).Append("`n") }
L '// @generated by tools/gen/Gen-Targets.ps1 from docs/phase7/targets.tsv. Do not edit.'
L '//! Target, trash and friendly NPC species of the encounter logics of the C# parser.'
L ''
L '/// The NPC lists of one encounter logic (`LogLogic.GetTargetsIDs` and relatives).'
L '#[derive(Debug, Clone, Copy)]'
L 'pub struct Logic {'
L '    /// Trigger id of the log (the species the logic is chosen by).'
L '    pub trigger_id: i32,'
L '    /// Name of the C# class.'
L '    pub name: &''static str,'
L '    /// Species that are targets, in the order C# lists them.'
L '    pub targets: &''static [i32],'
L '    /// Species that are trash mobs.'
L '    pub trash: &''static [i32],'
L '    /// Species that are friendly NPCs outside the squad.'
L '    pub friendly: &''static [i32],'
L '    /// Sort key per target species (`GetTargetsSortIDs`); unlisted species sort last.'
L '    pub sort: &''static [(i32, i32)],'
L '    /// Species that never get breakbar phases (`ForbidBreakbarPhasesFor`).'
L '    pub no_breakbar: &''static [i32],'
L '}'
L ''
L '/// All logics, ordered by trigger id.'
L 'pub const LOGICS: &[Logic] = &['
foreach ($g in ($rows | Group-Object { [int]$_.Trigger } | Sort-Object { [int]$_.Name })) {
    $r = $g.Group
    $name = ($r | Select-Object -First 1).Logic
    $ids = { param($k) (($r | Where-Object { $_.Kind -eq $k } | Sort-Object { [int]$_.Index } | ForEach-Object { $_.Id }) -join ', ') }
    $sort = (($r | Where-Object { $_.Kind -eq 'sort' } | Sort-Object { [int]$_.Id } | ForEach-Object { "($($_.Id), $($_.Index))" }) -join ', ')
    L '    Logic {'
    L "        trigger_id: $($g.Name),"
    L "        name: `"$name`","
    L "        targets: &[$(& $ids 'target')],"
    L "        trash: &[$(& $ids 'trash')],"
    L "        friendly: &[$(& $ids 'friendly')],"
    L "        sort: &[$sort],"
    L "        no_breakbar: &[$(& $ids 'nobreakbar')],"
    L '    },'
}
L '];'
L ''
L '/// The logic of a trigger id.'
L '#[must_use]'
L 'pub fn logic(trigger_id: i32) -> Option<&''static Logic> {'
L '    LOGICS'
L '        .binary_search_by_key(&trigger_id, |l| l.trigger_id)'
L '        .ok()'
L '        .map(|i| &LOGICS[i])'
L '}'
[IO.File]::WriteAllText($Out, $sb.ToString())
