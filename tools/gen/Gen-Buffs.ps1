<#
 Generates rust/ei-data/src/generated/buffs.rs from docs/phase4/buffs.tsv (written by
 `GW2EIParserReference --dump-data`, so it holds the values the C# parser really uses).
 The enums Source, BuffClassification and BuffStackType are derived from the values that occur.
 Usage: Gen-Buffs.ps1 [-Tsv <buffs.tsv>] [-Out <buffs.rs>]
#>
param([string]$Tsv = '', [string]$Out = '')
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path))
if (-not $Tsv) { $Tsv = Join-Path $root 'docs\phase4\buffs.tsv' }
if (-not $Out) { $Out = Join-Path $root 'rust\ei-data\src\generated\buffs.rs' }
$rows = Import-Csv -Delimiter "`t" -LiteralPath $Tsv -Encoding UTF8
if (-not $rows) { throw 'no rows' }

function Rust-Str([string]$s) { '"' + ($s.Replace('\', '\\').Replace('"', '\"')) + '"' }
function Variants($values) { ($values | Sort-Object -Unique) }
$sources = Variants ($rows | ForEach-Object { $_.Sources -split '\|' })
$classes = Variants ($rows.Classification)
$stacks = Variants ($rows.StackType)
foreach ($v in @($sources) + @($classes) + @($stacks)) { if ($v -notmatch '^[A-Za-z][A-Za-z0-9]*$') { throw "bad variant name: $v" } }

$sb = New-Object System.Text.StringBuilder
function L([string]$s) { [void]$sb.Append($s).Append("`n") }
L '// @generated by tools/gen/Gen-Buffs.ps1 from docs/phase4/buffs.tsv. Do not edit.'
L '//! Buff definitions of the C# parser (`Buff` objects of all static buff lists), same values.'
L ''
foreach ($e in @(@('Source', $sources, 'Source of a buff (`ParserHelper.Source`): who can cause it.'), @('Classification', $classes, '`Buff.BuffClassification`.'), @('StackType', $stacks, '`ArcDPSEnums.BuffStackType`.'))) {
    L "/// $($e[2])"
    L '#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]'
    L "pub enum $($e[0]) {"
    foreach ($v in $e[1]) { L "    $v," }
    L '}'
    L ''
}
L '/// One buff definition.'
L '#[derive(Debug, Clone, Copy, PartialEq, Eq)]'
L 'pub struct BuffDef {'
L '    /// Name of the list in the C# code the buff is defined in, e.g. `CommonBuffs.Boons`.'
L '    pub list: &''static str,'
L '    pub name: &''static str,'
L '    pub id: i64,'
L '    pub classification: Classification,'
L '    pub sources: &''static [Source],'
L '    pub stack_type: StackType,'
L '    pub capacity: i32,'
L '    /// First and last GW2 build the buff exists in (`u64::MAX` = no end).'
L '    pub min_build: u64,'
L '    pub max_build: u64,'
L '    /// First and last arcdps build the buff exists in.'
L '    pub min_evtc_build: i32,'
L '    pub max_evtc_build: i32,'
L '    pub link: &''static str,'
L '}'
L ''
L "pub static BUFFS: [BuffDef; $(@($rows).Count)] = ["
foreach ($r in $rows) {
    $src = ($r.Sources -split '\|' | ForEach-Object { "Source::$_" }) -join ', '
    $max = if ($r.MaxBuild -eq '18446744073709551615') { 'u64::MAX' } else { $r.MaxBuild }
    $minE = if ($r.MinEvtcBuild -eq '-2147483648') { 'i32::MIN' } else { $r.MinEvtcBuild }
    $maxE = if ($r.MaxEvtcBuild -eq '2147483647') { 'i32::MAX' } else { $r.MaxEvtcBuild }
    L "    BuffDef { list: $(Rust-Str $r.List), name: $(Rust-Str $r.Name), id: $($r.Id), classification: Classification::$($r.Classification), sources: &[$src], stack_type: StackType::$($r.StackType), capacity: $($r.Capacity), min_build: $($r.MinBuild), max_build: $max, min_evtc_build: $minE, max_evtc_build: $maxE, link: $(Rust-Str $r.Link) },"
}
L '];'
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
Write-Output "buffs=$(@($rows).Count) sources=$(@($sources).Count) classes=$(@($classes).Count) stacks=$(@($stacks).Count)"
