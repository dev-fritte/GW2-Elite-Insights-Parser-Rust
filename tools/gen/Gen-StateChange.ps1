<#
 Generates rust/ei-core/src/generated/state_change.rs from the StateChange enum of ArcDPSEnums.cs.
 The Rust constants are never typed by hand, so they follow the C# source after every arcdps update.
 Usage: Gen-StateChange.ps1 [-Source <ArcDPSEnums.cs>] [-Out <state_change.rs>]
#>
param(
    [string]$Source = '',
    [string]$Out = ''
)
$root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path))
if (-not $Source) { $Source = Join-Path $root 'GW2EI.Library\GW2EI.Services\GW2EIEvtcParser\ParserHelpers\ArcDPSEnums.cs' }
if (-not $Out) { $Out = Join-Path $root 'rust\ei-core\src\generated\state_change.rs' }

$text = Get-Content -Raw -LiteralPath $Source
if ($text -notmatch '(?s)public enum StateChange : byte\s*\{(?<body>.*?)\}\s*;') { throw 'StateChange enum not found' }
$next = 0
$items = foreach ($line in ($Matches['body'] -split "`n")) {
    $l = ($line -replace '//.*$', '').Trim().TrimEnd(',')
    if (-not $l) { continue }
    if ($l -match '^(?<name>\w+)\s*=\s*(?<value>\d+)$') { $next = [int]$Matches['value'] }
    elseif ($l -match '^(?<name>\w+)$') { }
    else { throw "cannot parse enum line: $l" }
    [pscustomobject]@{ Name = $Matches['name']; Value = $next }
    $next++
}
function ToScreaming([string]$n) { ($n -creplace '([a-z0-9])([A-Z])', '$1_$2' -creplace '([A-Z]+)([A-Z][a-z])', '$1_$2').ToUpperInvariant() }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// @generated by tools/gen/Gen-StateChange.ps1 from ArcDPSEnums.cs (enum StateChange). Do not edit.')
[void]$sb.AppendLine('//! Values of the arcdps `is_statechange` byte, named like the C# `StateChange` enum.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#![allow(missing_docs)]')
[void]$sb.AppendLine('')
foreach ($i in $items) {
    [void]$sb.AppendLine(('pub const {0}: u8 = {1};' -f (ToScreaming $i.Name), $i.Value))
}
$dir = Split-Path -Parent $Out
New-Item -ItemType Directory -Force -Path $dir | Out-Null
[System.IO.File]::WriteAllText($Out, ($sb.ToString() -replace "`r`n", "`n"), (New-Object System.Text.UTF8Encoding($false)))
"{0} constants -> {1}" -f @($items).Count, $Out
